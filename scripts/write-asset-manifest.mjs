// Regenerates docs/asset-manifest.md from the media manifest and processed dimensions.
// Usage: npm run docs:assets
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
const manifest = read('src/data/media-manifest.json');
const dims = read('src/data/media.generated.json');

const walk = (p) => (fs.statSync(p).isDirectory() ? fs.readdirSync(p).flatMap((f) => walk(path.join(p, f))) : [p]);
const sources = ['src/data', 'src/app', 'src/components']
  .flatMap((d) => walk(path.join(root, d)))
  .filter((f) => /\.tsx?$/.test(f))
  .map((f) => [path.relative(path.join(root, 'src'), f).replace(/\.tsx?$/, ''), fs.readFileSync(f, 'utf8')]);

const usedIn = (id) =>
  sources
    .filter(([, s]) => s.includes(`'${id}'`) || s.includes(`"${id}"`))
    .map(([f]) => f)
    .slice(0, 3)
    .join(', ') || '—';

const rows = [
  ...manifest.images.map((e) => `| \`${e.id}\` | ${dims[e.id].width}×${dims[e.id].height} | ${e.photographer} | ${e.unsplashId} | ${usedIn(e.id)} | ${e.alt} |`),
  ...manifest.derived.map((e) => `| \`${e.id}\` | ${dims[e.id].width}×${dims[e.id].height} | *Simulation* | derived from \`${e.from}\` | ${usedIn(e.id)} | ${e.alt} |`),
];

const doc = `# Asset Manifest

Generated by \`npm run docs:assets\` from \`src/data/media-manifest.json\` and \`src/data/media.generated.json\`. Run \`npm run images\` first after changing the manifest.

## Licensing

- All photographs: **Unsplash License** (https://unsplash.com/license) — free for commercial use, no permission or attribution required. Photographers are credited on \`/credits\` regardless.
- Unsplash+ (premium) images were deliberately excluded.
- Sources are downloaded once into \`.cache/images-src/\` (gitignored) and re-encoded to \`public/images/\` (max 2400 px, mozjpeg q80). \`next/image\` serves AVIF/WebP variants at runtime.
- **Simulated asset:** \`paint-before-simulated\` is generated from \`paint-macro-brown\` by \`scripts/process-images.mjs\` (desaturation, haze, procedurally drawn swirl arcs). It is labelled as a simulation wherever it appears.

## Replace before production

1. **All portfolio imagery.** Case studies currently pair stock photographs with illustrative narratives. Replace with the studio’s own documentation, shot under consistent lighting — ideally matched before/after pairs from a fixed tripod position.
2. **The before/after pair** — replace with a genuine matched pair from a real correction.
3. **Studio and team photography** for \`/about\` (the current images are generic garages).
4. **Hero film (optional)** — see \`public/videos/README.md\`.
5. Several stock photographs show legible number plates; real client imagery should have plates removed or blurred.

## Art direction for replacement photography

Low-key studio lighting, black or charcoal backgrounds, a single dominant light source describing the bodywork; macro detail of paint, leather and process; no wide-angle distortion; consistent colour temperature (≈ 5000 K); minimum 2400 px on the long edge.

## Inventory (${rows.length} images)

| ID | Size (px) | Photographer | Unsplash photo ID | Used in | Alt text |
|---|---|---|---|---|---|
${rows.join('\n')}

Other generated assets: \`public/og-default.jpg\` (Open Graph card, 1200×630, from \`hero-studio\`) and \`src/app/icon.svg\` / \`public/icon.svg\` (monogram).
`;

fs.writeFileSync(path.join(root, 'docs/asset-manifest.md'), doc);
console.log(`docs/asset-manifest.md — ${rows.length} images`);
